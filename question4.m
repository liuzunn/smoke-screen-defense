%% ----------------------- local function definitions -----------------------
function Pm = missile_pos(t)
    % Returns missile position at time t
    % Uses persistent variables from outer workspace via evalin
    P_m1_0 = evalin('base','P_m1_0');
    v_m1 = evalin('base','v_m1');
    Pm = P_m1_0 + v_m1 * t;
end

function d = point_to_segment_distance(C, Pm, Pt)
    % shortest distance from point C to segment Pm-Pt
    v = (Pt - Pm);
    denom = dot(v,v);
    if denom == 0
        s = 0;
    else
        s = dot((C - Pm), v) / denom;
        s = max(0, min(1, s));
    end
    proj = Pm + s * v;
    d = norm(C - proj);
end

function C = cloud_center(Pc0, t_expl, t)
    % cloud center at time t (Pc0 is center at explosion)
    cloud_sink_v = evalin('base','cloud_sink_v');
    dt = t - t_expl;
    C = Pc0 + [0,0,-cloud_sink_v*dt];
end

function val = F_of_t(t, Pc0, t_expl)
    % F(t) = d(t) - cloud_r, with large positive if t outside effective interval
    cloud_r = evalin('base','cloud_r');
    cloud_life = evalin('base','cloud_life');
    if t < t_expl || t > t_expl + cloud_life || t > evalin('base','t_missile_arrival')
        val = 1e6;
        return;
    end
    Pm = missile_pos(t);
    C = cloud_center(Pc0, t_expl, t);
    d = point_to_segment_distance(C, Pm, evalin('base','P_target'));
    val = d - cloud_r;
end

function [intervals, total] = compute_intervals_and_measure(Pc0, t_expl, dt_eval)
    % Compute intervals where F(t) <= 0 on [t_expl, min(t_expl+life, missile_arrival)]
    if nargin < 3, dt_eval = 0.002; end
    cloud_life = evalin('base','cloud_life');
    t_end = min(t_expl + cloud_life, evalin('base','t_missile_arrival'));
    t_start = t_expl;
    intervals = [];
    total = 0;
    if t_start >= t_end
        return;
    end
    tgrid = t_start:dt_eval:t_end;
    F = arrayfun(@(tt) F_of_t(tt, Pc0, t_expl), tgrid);
    mask = F <= 0;
    inint = false; left = NaN;
    for i=1:length(tgrid)
        if mask(i) && ~inint
            inint = true; left = tgrid(i);
        elseif ~mask(i) && inint
            inint = false; right = tgrid(max(1,i-1));
            intervals = [intervals; [left, right]];
        end
    end
    if inint
        intervals = [intervals; [left, tgrid(end)]];
    end
    % refine boundaries using fzero on sign changes
    roots = [];
    for i=1:length(tgrid)-1
        if F(i)*F(i+1) < 0
            a = tgrid(i); b = tgrid(i+1);
            try
                r = fzero(@(tt) F_of_t(tt,Pc0,t_expl), [a,b]);
                roots = [roots; r];
            catch
                % ignore
            end
        end
    end
    roots = unique(roots);
    if length(roots) >= 2 && mod(length(roots),2)==0
        intervals = reshape(roots,2,[])';
    end
    % catch narrow intervals
    if isempty(intervals)
        [Fmin, idxmin] = min(F);
        if Fmin <= 0
            tmin = tgrid(idxmin);
            left = max(t_start, tmin - 0.5); right = min(t_end, tmin + 0.5);
            tfine = linspace(left, right, 2001);
            Ff = arrayfun(@(tt) F_of_t(tt, Pc0, t_expl), tfine);
            ids = find(Ff <= 0);
            if ~isempty(ids)
                intervals = [intervals; [tfine(ids(1)), tfine(ids(end))]];
            end
        end
    end
    intervals = merge_intervals(intervals);
    if ~isempty(intervals)
        total = sum(intervals(:,2) - intervals(:,1));
    else
        total = 0;
    end
end

function [P_drop, Pc0, t_expl, intervals, J] = evaluate_single_bomb(uav_pos, theta_deg, v_u, t_drop, tau, dt_eval, refine)
    % Evaluate a single bomb configuration:
    % inputs: uav_pos (1x3), theta_deg, v_u, t_drop, tau
    % outputs: P_drop, Pc0, t_expl, intervals (nx2), J (total coverage time)
    if nargin < 7, refine = true; end
    theta = theta_deg * pi/180;
    uh = [cos(theta), sin(theta), 0];
    vvec = uh * v_u;
    P_drop = uav_pos + vvec * t_drop;
    t_expl = t_drop + tau;
    Pc0 = P_drop + vvec * tau + [0,0, -0.5*evalin('base','g')*(tau^2)];
    % feasibility checks
    if t_expl < 0 || Pc0(3) < 0 || t_expl > evalin('base','t_missile_arrival')
        intervals = []; J = 0;
        return;
    end
    [intervals, J] = compute_intervals_and_measure(Pc0, t_expl, dt_eval);
    if J > 0 && refine
        [intervals, J] = compute_intervals_and_measure(Pc0, t_expl, 0.001);
    end
end

function merged = merge_intervals(intervals)
    % merge overlapping or adjacent intervals (nx2 array)
    if isempty(intervals)
        merged = [];
        return;
    end
    if size(intervals,2)~=2
        error('intervals must be nx2');
    end
    % sort by left end
    intervals = sortrows(intervals,1);
    merged = intervals(1,:);
    for i=2:size(intervals,1)
        a = intervals(i,1); b = intervals(i,2);
        if a <= merged(end,2) + 1e-8
            merged(end,2) = max(merged(end,2), b);
        else
            merged = [merged; [a,b]];
        end
    end
end

function [union_intv, total] = union_intervals(list_of_interval_lists)
    % union of multiple interval lists. input: cell array where each cell is nx2
    all = [];
    for i=1:numel(list_of_interval_lists)
        ints = list_of_interval_lists{i};
        if ~isempty(ints)
            all = [all; ints];
        end
    end
    if isempty(all)
        union_intv = [];
        total = 0;
        return;
    end
    union_intv = merge_intervals(all);
    total = sum(union_intv(:,2) - union_intv(:,1));
end

function val = neg_unionJ_fixed(x, UAV_POS_local, fixed_params, eval_single_fun)
    % x = [td1,ta1,td2,ta2,td3,ta3]
    % fixed_params: 3x2 [theta,v]
    % return negative unionJ (for minimization)
    % penalize infeasible
    for u=1:3
        td = x(2*u-1); ta = x(2*u);
        if td < 0 || ta < 0 || (td+ta) > evalin('base','t_missile_arrival')
            val = 1e3; return;
        end
    end
    intervals = cell(1,3);
    for u=1:3
        theta = fixed_params(u,1); v = fixed_params(u,2);
        [~,~,~,ints,~] = eval_single_fun(UAV_POS_local(u,:), theta, v, x(2*u-1), x(2*u), 0.002, false);
        intervals{u} = ints;
    end
    [~, J] = union_intervals(intervals);
    val = -J;
end